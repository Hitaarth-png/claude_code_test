"""Build the interactive city plan for every city in cities.yaml, then write a
linked index page at <output_dir>/index.html.

Usage:  python scripts/run_all.py [--no-sample] [--only slug1,slug2]
"""
from __future__ import annotations

import argparse

from common import ROOT, list_cities, load_config, resolve
from run_pipeline import run_for_city


def build_index(results):
    """results: list of (slug, name, ok)."""
    cards = []
    for slug, name, ok in results:
        if ok:
            cards.append(f'<li><a href="{slug}/city_plan.html">{name}</a></li>')
        else:
            cards.append(f'<li><span class="fail">{name} — build failed</span></li>')
    html = (
        "<!doctype html><meta charset='utf-8'><title>City Plans</title>"
        "<style>body{font-family:sans-serif;max-width:640px;margin:40px auto;padding:0 16px;}"
        "h1{font-size:20px;} li{margin:6px 0;font-size:16px;} .fail{color:#a00;}</style>"
        "<h1>Interactive City Plans</h1><ul>" + "".join(cards) + "</ul>"
        "<p style='color:#777;font-size:13px'>Generated by scripts/run_all.py — "
        "layer status (real vs synthetic) per city is noted in each map and the README.</p>")
    out_dir = resolve(load_config()["output_dir"]).parent   # base output/ dir
    out_dir.mkdir(parents=True, exist_ok=True)
    index = out_dir / "index.html"
    index.write_text(html)
    return index


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--no-sample", action="store_true")
    ap.add_argument("--only", default=None, help="Comma-separated subset of city slugs")
    args = ap.parse_args()

    reg = list_cities()["cities"]
    slugs = args.only.split(",") if args.only else list(reg)

    results = []
    for slug in slugs:
        try:
            run_for_city(slug.strip(), no_sample=args.no_sample)
            results.append((slug, reg[slug]["name"], True))
        except SystemExit as e:
            print(f"[{slug}] skipped: {e}")
            results.append((slug, reg[slug]["name"], False))

    index = build_index(results)
    ok = sum(1 for *_, s in results if s)
    print(f"\nBuilt {ok}/{len(results)} cities. Index: {index}")


if __name__ == "__main__":
    main()
